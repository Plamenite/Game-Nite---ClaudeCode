/**
 * Generates OUR OWN 10x10 board layout (not the layout of the classic
 * trademarked game). Properties:
 *   - 100 cells, the four corners are free spaces
 *   - the 48 non-Jack cards each appear exactly twice, no Jacks
 *   - a card's two copies are in different rows AND columns, at least
 *     `MIN_DISTANCE` steps apart, so the board plays evenly
 *
 * Run once, paste the printed literal into src/fiverow-board.ts. Never
 * regenerate casually: a changed layout breaks saved games and stats.
 *
 *   npx tsx scripts/generate-fiverow-board.ts [seed]
 */
import { RANKS, SUITS, cardId, type Card } from '../src/cards.js';

const SIZE = 10;
const MIN_DISTANCE = 5;
const seed = Number(process.argv[2] ?? 20260922);

function mulberry32(a: number) {
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const random = mulberry32(seed);
const corners = new Set([0, SIZE - 1, SIZE * (SIZE - 1), SIZE * SIZE - 1]);
const nonJacks: Card[] = [];
for (const suit of SUITS) for (const rank of RANKS) if (rank !== 'J') nonJacks.push({ suit, rank });

function farEnough(a: number, b: number) {
  const ra = Math.floor(a / SIZE), ca = a % SIZE, rb = Math.floor(b / SIZE), cb = b % SIZE;
  return ra !== rb && ca !== cb && Math.abs(ra - rb) + Math.abs(ca - cb) >= MIN_DISTANCE;
}

function attempt(): (string | 'free')[] | null {
  const free: number[] = [];
  for (let i = 0; i < SIZE * SIZE; i++) if (!corners.has(i)) free.push(i);
  const layout: (string | 'free')[] = new Array(SIZE * SIZE).fill('free');
  const cards = nonJacks.slice().sort(() => random() - 0.5);
  for (const card of cards) {
    // pick the first cell at random, then a partner that is far enough away
    for (let tries = 0; tries < 50; tries++) {
      const i = Math.floor(random() * free.length);
      const partners = free.filter((c) => farEnough(free[i], c));
      if (partners.length === 0) continue;
      const j = free.indexOf(partners[Math.floor(random() * partners.length)]);
      const [a, b] = [free[i], free[j]];
      layout[a] = cardId(card);
      layout[b] = cardId(card);
      free.splice(Math.max(i, j), 1);
      free.splice(Math.min(i, j), 1);
      break;
    }
    if (layout.filter((c) => c === cardId(card)).length !== 2) return null;
  }
  return free.length === 0 ? layout : null;
}

let layout: (string | 'free')[] | null = null;
let restarts = 0;
while (!layout) { layout = attempt(); if (!layout) restarts++; if (restarts > 10000) throw new Error('gave up'); }

console.log(`// generated by scripts/generate-fiverow-board.ts with seed ${seed} (${restarts} restarts)`);
for (let r = 0; r < SIZE; r++) {
  console.log('  ' + layout.slice(r * SIZE, r * SIZE + SIZE).map((c) => `'${c}'`).join(', ') + ',');
}
